/** Build-time production metadata. No secrets, guessed domains, or browser calls. */
import { readFile, writeFile, unlink } from 'node:fs/promises';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const START = '<!-- ufodia-hosting:start -->';
const END = '<!-- ufodia-hosting:end -->';
const ROBOTS_MARKER = '# Generated by Ufodia hosting preparation.';
const SITEMAP_MARKER = '<!-- Generated by Ufodia hosting preparation. -->';
const escapeAttribute = (value) =>
  value.replaceAll('&', '&amp;').replaceAll('"', '&quot;').replaceAll('<', '&lt;').replaceAll('>', '&gt;');

/** Vercel supplies a hostname without protocol, path, query, credentials, or port. */
export function productionOrigin(value) {
  if (
    typeof value !== 'string' ||
    !value ||
    value !== value.trim() ||
    value.length > 253 ||
    /[\s<>"'\\/?:#@]/u.test(value)
  )
    throw new Error('Production requires a valid VERCEL_PROJECT_PRODUCTION_URL hostname.');
  const url = new URL('https://' + value);
  if (
    url.protocol !== 'https:' ||
    url.pathname !== '/' ||
    url.search ||
    url.hash ||
    url.port ||
    url.username ||
    url.password ||
    !url.hostname.includes('.') ||
    url.hostname === 'localhost' ||
    url.hostname.endsWith('.localhost') ||
    url.hostname.endsWith('.local') ||
    url.hostname.endsWith('.internal') ||
    /^\d+(?:\.\d+){3}$/.test(url.hostname)
  )
    throw new Error('Production requires a public DNS hostname, without a path or credentials.');
  if (!url.hostname.split('.').every((label) => /^[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?$/i.test(label)))
    throw new Error('Invalid production hostname.');
  return url.origin;
}

async function optionalRead(file) {
  try {
    return await readFile(file, 'utf8');
  } catch (error) {
    if (error.code === 'ENOENT') return null;
    throw error;
  }
}
function removeGeneratedBlock(html) {
  const begin = html.indexOf(START),
    end = html.indexOf(END);
  if (begin < 0 && end < 0) return html;
  if (begin < 0 || end < begin) throw new Error('Malformed generated hosting metadata block.');
  return html.slice(0, begin) + html.slice(end + END.length);
}
function robotsMeta(html) {
  return [...html.matchAll(/<meta\b[^>]*>/gi)]
    .filter(([tag]) => /\bname\s*=\s*(["'])robots\1/i.test(tag))
    .map(([tag]) => tag.match(/\bcontent\s*=\s*(["'])(.*?)\1/i)?.[2] ?? '')
    .join(',');
}

/** Prepare only a built dist directory. Preserve explicit source robots policies. */
export async function prepareHosting(directory, env = {}) {
  const isProduction = env.VERCEL_ENV === 'production';
  const origin = isProduction ? productionOrigin(env.VERCEL_PROJECT_PRODUCTION_URL) : null;
  const indexPath = path.join(directory, 'index.html');
  let html = removeGeneratedBlock(await readFile(indexPath, 'utf8'));
  if (!/<\/head\s*>/i.test(html)) throw new Error('Built index.html has no closing head element.');
  if (/<link\b[^>]*\brel\s*=\s*(["'])canonical\1/i.test(html))
    throw new Error(
      'Source already declares a canonical URL; review it before automated hosting preparation.',
    );
  const existingMeta = robotsMeta(html);
  const robotsPath = path.join(directory, 'robots.txt');
  const oldRobots = await optionalRead(robotsPath);
  const customRobots = oldRobots !== null && !oldRobots.startsWith(ROBOTS_MARKER);
  const blockedByMeta = /\b(noindex|none)\b/i.test(existingMeta);
  const sitemapPath = path.join(directory, 'sitemap.xml');
  const oldSitemap = await optionalRead(sitemapPath);
  if (oldSitemap !== null && !oldSitemap.includes(SITEMAP_MARKER))
    throw new Error('Custom sitemap.xml found; review it before automated hosting preparation.');
  // A custom robots file needs a deliberate, separately reviewed indexing policy.
  const indexable = isProduction && !blockedByMeta && !customRobots;
  const canonical = origin ? origin + '/' : null;
  const tags = [];
  if (canonical) {
    const escaped = escapeAttribute(canonical);
    tags.push(`<link rel="canonical" href="${escaped}">`, `<meta property="og:url" content="${escaped}">`);
  }
  if (!isProduction) tags.push('<meta name="robots" content="noindex,nofollow">');
  // Production keeps any explicit source robots meta directive untouched.
  const generated = `${START}\n${tags.join('\n')}\n${END}`;
  html = html.replace(/<\/head\s*>/i, `${generated}\n</head>`);
  // Social previews need an absolute image URL; a root-relative source path is resolved against production only.
  if (origin)
    html = html.replace(
      /(<meta\b[^>]*\bproperty\s*=\s*(["'])og:image\2[^>]*\bcontent\s*=\s*(["']))\/(?!\/)([^"']*)\3/gi,
      (_m, prefix, _q, quote, file) => `${prefix}${escapeAttribute(origin)}/${file}${quote}`,
    );
  await writeFile(indexPath, html, 'utf8');
  if (!customRobots) {
    const policy = !isProduction ? 'User-agent: *\nDisallow: /\n' : 'User-agent: *\nAllow: /\n';
    await writeFile(
      robotsPath,
      `${ROBOTS_MARKER}\n${policy}${indexable ? `Sitemap: ${canonical}sitemap.xml\n` : ''}`,
      'utf8',
    );
  }

  if (indexable) {
    await writeFile(
      sitemapPath,
      `<?xml version="1.0" encoding="UTF-8"?>\n${SITEMAP_MARKER}\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"><url><loc>${escapeAttribute(canonical)}</loc></url></urlset>\n`,
      'utf8',
    );
  } else if (oldSitemap !== null) {
    await unlink(sitemapPath);
  }
  return { production: isProduction, canonical, indexable, customRobots };
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  const result = await prepareHosting(path.resolve(import.meta.dirname, '../dist'), process.env);
  console.log(
    result.production
      ? `Prepared production hosting metadata for ${result.canonical}${result.indexable ? '' : ' (custom indexing policy preserved)'}`
      : 'Prepared a non-indexable local/preview build; no production sitemap.',
  );
}
